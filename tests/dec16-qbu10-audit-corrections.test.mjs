import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
const targetId="ks754sam381sspwkcnz5bdjfj5812kcp";
const evidenceId="jn6e00b0dc20fdc0893af80e7c2d5f21";
test("Dec 16 QBU-10 report stays attributed and drops unsupported exact time",()=>{
 const timeline=readFileSync("data/timeline/2025-12.jsonl","utf8").trim().split(/\r?\n/u).map(JSON.parse);
 const event=timeline.find(x=>x.id===targetId);
 assert.equal(event.date,"2025-12-16");
 assert.equal(event.timeOfDay,undefined);
 assert.deepEqual(event.evidenceIds,[evidenceId]);
 assert.match(event.title,/Militarnyi Reports/u);
 assert.match(event.description,/citing a photograph published by military analyst War Noir/u);
 assert.match(event.description,/claim about battlefield use is attributed/u);
 assert.doesNotMatch(event.description,/have been verified|verified using/u);
 const news=readFileSync("data/news/2025-12.jsonl","utf8").trim().split(/\r?\n/u).map(JSON.parse);
 const article=news.find(x=>x.id===evidenceId);
 assert.equal(article.credibility,70);
 assert.match(article.summary,/citing a War Noir photograph/u);
});
