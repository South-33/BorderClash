import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
const targetId="ks74spsahtkn6w5g3zd0ea2nns88zvy3";
const evidenceId="db5b788c9bac942a1e32c4d419de41c8";
test("Jun 19 row records the verified report without inventing a deportation date",()=>{
 const timeline=readFileSync("data/timeline/2026-06.jsonl","utf8").trim().split(/\r?\n/u).map(JSON.parse);
 const event=timeline.find(x=>x.id===targetId);
 assert.equal(event.date,"2026-06-19");
 assert.equal(event.timeOfDay,undefined);
 assert.deepEqual(event.evidenceIds,[evidenceId]);
 assert.match(event.title,/^Khmer Times Reports/u);
 assert.match(event.description,/88 Cambodians/u);
 assert.match(event.description,/does not state when the deportation occurred/u);
 assert.doesNotMatch(event.description,/women and children|including women|14:00/u);
 assert.doesNotMatch(event.titleTh+event.descriptionTh+event.titleKh+event.descriptionKh,/�/u);
 const news=readFileSync("data/news/2026-06.jsonl","utf8").trim().split(/\r?\n/u).map(JSON.parse);
 const article=news.find(x=>x.id===evidenceId);
 assert.equal(article.sourceUrl,"https://t.me/s/khmertimesbreakingnews?before=91139");
});
